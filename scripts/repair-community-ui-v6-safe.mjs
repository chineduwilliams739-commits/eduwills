import fs from 'node:fs';
const file='app/dashboard/community/group/page.tsx';
let g=fs.readFileSync(file,'utf8');
const canonical='[isMember,setIsMember]=useState(false),[joining,setJoining]=useState(false),[isLocked,setIsLocked]=useState(false),[members,setMembers]=useState<any[]>([])';
const line=' const '+canonical+';';
const alt='\nconst '+canonical+';';
let n=g.split(line).length-1;
if(!n)n=g.split(alt).length-1;
if(!n)throw new Error('GROUP_UI_V6_CANONICAL_STATE_MISSING');
if(n>1){g=g.split(line).join('');g=g.split(alt).join('');}
const anchor='\n const [unread,setUnread]=useState(0);';
if(!g.includes(anchor))throw new Error('GROUP_UI_V6_UNREAD_ANCHOR_MISSING');
g=g.replace(anchor,anchor+'\n'+line);
if(g.split('[isMember,setIsMember]').length-1!==1)throw new Error('GROUP_UI_V6_MEMBER_STATE_NOT_CANONICAL');
if(g.split('[joining,setJoining]').length-1!==1)throw new Error('GROUP_UI_V6_JOINING_STATE_NOT_CANONICAL');
if(g.split('[isLocked,setIsLocked]').length-1!==1)throw new Error('GROUP_UI_V6_LOCK_STATE_NOT_CANONICAL');
if(g.split('[members,setMembers]').length-1!==1)throw new Error('GROUP_UI_V6_MEMBERS_STATE_NOT_CANONICAL');
if(!g.includes('async function joinGroup()'))throw new Error('GROUP_UI_V6_JOIN_MISSING');
if(!g.includes('GROUP INFO'))throw new Error('GROUP_UI_V6_INFO_MISSING');
if(!g.includes('>MEMBERS</button>'))throw new Error('GROUP_UI_V6_MEMBERS_TAB_MISSING');
if(!g.includes('aria-label="Write a message"'))throw new Error('GROUP_UI_V6_COMPOSER_MISSING');
if(g.includes('capture="environment"'))throw new Error('GROUP_UI_V6_CAMERA_CAPTURE_REMAINS');
fs.writeFileSync(file,g);
console.log('Community UI v6 safe standalone deduplication passed.');
