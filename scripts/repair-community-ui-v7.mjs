import fs from 'node:fs';
const group='app/dashboard/community/group/page.tsx';
const g=fs.readFileSync(group,'utf8');
const hasInlineInfo=g.includes('GROUP INFO')&&g.includes('setMembersOpen(true)')&&g.includes('setMembersOpen(false)');
const hasMembersState=g.includes('[membersOpen,setMembersOpen]');
const hasComposer=g.includes('aria-label="Write a message"')&&g.includes("writingMode:'horizontal-tb'");
if(!hasMembersState)throw new Error('GROUP_MEMBERS_TAB_STATE_MISSING');
if(!hasInlineInfo)throw new Error('GROUP_INLINE_INFO_NOT_FOUND');
if(!hasComposer)throw new Error('GROUP_COMPOSER_HORIZONTAL_FLOW_MISSING');
console.log('Community UI v7: inline Group Info / INFO / MEMBERS and horizontal composer detected; repair is idempotent.');
